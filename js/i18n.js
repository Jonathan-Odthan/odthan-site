(function(){
  const STORAGE_KEY = "odthan_lang";
  function getLang(){
    return localStorage.getItem(STORAGE_KEY) || document.documentElement.lang || "ht";
  }
  function applyLang(lang){
    const dict = ODTHAN_I18N[lang] || ODTHAN_I18N.ht;
    document.documentElement.lang = lang === "ht" ? "ht" : "fr";
    document.querySelectorAll("[data-i18n]").forEach(function(el){
      const key = el.getAttribute("data-i18n");
      if(dict[key]) el.textContent = dict[key];
    });
    document.querySelectorAll("[data-i18n-attr]").forEach(function(el){
      el.getAttribute("data-i18n-attr").split(";").forEach(function(pair){
        const [attr, key] = pair.split(":");
        if(attr && key && dict[key]) el.setAttribute(attr.trim(), dict[key.trim()]);
      });
    });
    document.querySelectorAll(".lang-switch button, .mobile-nav .lang-switch button").forEach(function(btn){
      btn.classList.toggle("is-active", btn.getAttribute("data-lang") === lang);
    });
    localStorage.setItem(STORAGE_KEY, lang);
  }
  document.addEventListener("DOMContentLoaded", function(){
    applyLang(getLang());
    document.querySelectorAll("[data-lang]").forEach(function(btn){
      btn.addEventListener("click", function(){
        applyLang(btn.getAttribute("data-lang"));
      });
    });
  });
})();
